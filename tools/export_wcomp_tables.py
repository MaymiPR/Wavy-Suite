"""Writes plugins/WComp/WCompTables.h from the WComp measurements: the static curve's constants (knee_model), the makeup
slopes per ratio (makeup.csv), the release law (release_law.json, fitted by nulltest/ident_hc_release2.py and
ident_hc_real.py) and the Analog modes (analog_model.json from nulltest/fit_hc_analog2.py, analog_noise.csv).

    python tools/export_wcomp_tables.py
"""
import os, json
import numpy as np

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
M = os.path.join(ROOT, 'measurements', 'hcomp')


def main():
    res = json.load(open(os.path.join(M, 'results.json')))
    km = res['knee_model']
    mk = np.loadtxt(os.path.join(M, 'makeup.csv'), delimiter=',', skiprows=1)
    rats, slopes = [], []
    for r in sorted(set(mk[:, 1])):
        s = mk[(mk[:, 1] == r) & (mk[:, 0] <= -12)]
        k, b = np.polyfit(s[:, 0], s[:, 2], 1)
        rats.append(r); slopes.append(max(0.0, -k))
    mr = np.loadtxt(os.path.join(M, 'makeup_release.csv'), delimiter=',', skiprows=1)
    sel = mr[(mr[:, 0] == -30.0) & (mr[:, 1] == 4.0)]
    base = sel[sel[:, 2] == 100.0][0, 3]
    relMs, relF = sel[:, 2], sel[:, 3] / base
    sh = np.loadtxt(os.path.join(M, 'static_h.csv'), delimiter=',', skiprows=1)
    st = {'x': sh[:, 0], 'h': sh[:, 1]}
    law = json.load(open(os.path.join(M, 'release_law.json')))
    w0 = json.load(open(os.path.join(M, 'release_w0.json')))
    nS = len(w0['S'])
    kn, x = law['knots'], np.array(law['x'])
    parts, i = {}, 0
    for k in law['order']:
        parts[k] = x[i:i + len(kn[k])]; i += len(kn[k])
    def lit(t):
        s = '%.9g' % float(t)
        return (s if ('.' in s or 'e' in s) else s + '.0') + 'f'
    f = lambda v: ', '.join(lit(t) for t in v)
    L = ['#pragma once', '// Generated by tools/export_wcomp_tables.py from measurements/hcomp (the reference H-Comp). Do not edit.',
         'namespace wcomp::tables', '{',
         '// static curve: x = (1 - 1/ratio) * max(0, 20 log10(peak + 0.001) - threshold), GR = h(x) (measured: the curves of',
         '// every threshold and ratio collapse onto one h, 0.014 dB RMS); beyond the table h(x) = x - (x_last - h_last)',
         'constexpr float floorLevel = 0.001f;',
         'constexpr int staticCount = %d;' % len(st['x']),
         'constexpr float staticX[] = { %s };' % f(st['x']),
         'constexpr float staticH[] = { %s };' % f(st['h']),
         '// makeup = slope(ratio) * max(0, -9 - threshold) dB',
         'constexpr int makeupCount = %d;' % len(rats),
         'constexpr float makeupRatio[] = { %s };' % f(rats),
         'constexpr float makeupSlope[] = { %s };' % f(slopes),
         '// ... measured at Release 100 ms; at other release times it is scaled by makeupScale(release), the same for every',
         '// threshold and ratio (interpolated in log release)',
         'constexpr int makeupRelCount = %d;' % len(relMs),
         'constexpr float makeupRelMs[] = { %s };' % f(relMs),
         'constexpr float makeupRelScale[] = { %s };' % f(relF),
         '// release law (dB / s, natural-log values on knots): the slow state S releases at fs(S) / release + as(S) and',
         '// charges toward the output R as a one-pole on the linear gain (time constant crestMs); R falls at the same law',
         '// with the effective release min(release, release * w0(S), K / (R - S)^p)',
         'constexpr int fsCount = %d, asCount = %d, w0Count = %d;' % (len(kn['Fs']), len(kn['As']), nS),
         'constexpr float fsKnot[] = { %s };' % f(kn['Fs']), 'constexpr float fsLog[] = { %s };' % f(parts['Fs']),
         'constexpr float asKnot[] = { %s };' % f(kn['As']), 'constexpr float asLog[] = { %s };' % f(parts['As']),
         'constexpr float w0Knot[] = { %s };' % f(w0['S']), 'constexpr float w0Log[] = { %s };' % f(w0['z'][:nS]),
         'constexpr float relSeedMs = %s, relSeedExp = %s, crestMs = %s;' % (lit(np.exp(w0['z'][nS])), lit(w0['z'][nS + 1]), lit(w0['z'][nS + 2])),
         ''] + release3(lit, f) + analog(lit, f) + ['}']
    out = os.path.join(ROOT, 'plugins', 'WComp', 'WCompTables.h')
    open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
    print('wrote', out)


def release3(lit, f):
    p = os.path.join(M, 'release_law3.json')
    have = os.path.exists(p)
    # without a fit: placeholders (hasRelease3 false selects the second form)
    d = json.load(open(p)) if have else {'FX': [0, 1], 'AX': [0, 1], 'RK': [0, 1], 'SK': [0, 1], 'q': [0.0] * 9}
    q = np.array(d['q'])
    nF, nA, nR, nS = len(d['FX']), len(d['AX']), len(d['RK']), len(d['SK'])
    return ['// release law, third form (nulltest/ident_hc_rel3.py): R falls at fs3(R) / release + as3(R) + ff3(R, S) dB/s, S',
            '// (charging toward R at the time constant crest3Ms) at fs3(S) / release + as3(S); natural-log values, ff3 bilinear',
            'constexpr bool hasRelease3 = %s;' % ('true' if have else 'false'),
            'constexpr int fs3Count = %d, as3Count = %d, ff3R = %d, ff3S = %d;' % (nF, nA, nR, nS),
            'constexpr float fs3Knot[] = { %s };' % f(d['FX']), 'constexpr float fs3Log[] = { %s };' % f(q[:nF]),
            'constexpr float as3Knot[] = { %s };' % f(d['AX']), 'constexpr float as3Log[] = { %s };' % f(q[nF:nF + nA]),
            'constexpr float crest3Ms = %s;' % lit(np.exp(q[nF + nA])),
            'constexpr float ff3RKnot[] = { %s };' % f(d['RK']), 'constexpr float ff3SKnot[] = { %s };' % f(d['SK']),
            'constexpr float ff3Log[] = { %s };' % f(q[nF + nA + 1:nF + nA + 1 + nR * nS]), '']


def analog(lit, f):
    am = json.load(open(os.path.join(M, 'analog_model.json')))
    nz = np.loadtxt(os.path.join(M, 'analog_noise.csv'), delimiter=',', skiprows=1)
    NL, N1, N2, kn = am['NL'], am['N1'], am['N2'], am['knots']
    pairs = lambda v: ', '.join('{ %s, %s }' % (lit(np.exp(v[i])), lit(np.exp(v[i + 1]))) for i in range(0, len(v), 2))
    L = ['// Analog modes: y = (1 + gain) L(x) + H2( g( H1(x) ) ) + noise; sections { fz, fp } in Hz of (1 + s/wz) / (1 + s/wp),',
         '// g on analogKnot (piecewise linear, linear beyond the ends), noise PSD in dB re 1 / Hz (one-sided) on analogNoiseHz',
         'constexpr int analogModes = 4, analogLin = %d, analogPre = %d, analogPost = %d, analogKnots = %d, analogNoiseBands = %d;'
         % (NL, N1, N2, len(kn), len(nz)),
         'constexpr float analogKnot[] = { %s };' % f(kn),
         'constexpr float analogNoiseHz[] = { %s };' % f(nz[:, 0]),
         '// bpHz, bpQ: a band-pass (s / (Q w0)) / (s^2 / w0^2 + s / (Q w0) + 1) before H1 (bpHz 0: none)',
         'struct AnalogMode { float gain; float bpHz, bpQ; float lin[analogLin][2]; float pre[analogPre][2]; float post[analogPost][2];',
         '                    float g[analogKnots]; float noiseDb[analogNoiseBands]; };',
         'constexpr AnalogMode analog[analogModes] = {']
    for m in (1, 2, 3, 4):
        q = np.array(am['modes'][str(m)])
        i = 0
        lL = q[i:i + 2 * NL]; i += 2 * NL
        l1 = q[i:i + 2 * N1]; i += 2 * N1
        l2 = q[i:i + 2 * N2]; i += 2 * N2
        gain = q[i]; i += 1
        tab = q[i:i + len(kn)]; i += len(kn)
        bp = (np.exp(q[i]), np.exp(q[i + 1])) if m in am.get('bandpass_modes', []) else (0.0, 0.0)
        L += ['    { %s, %s, %s, { %s }, { %s }, { %s },' % (lit(gain), lit(bp[0]), lit(bp[1]), pairs(lL), pairs(l1), pairs(l2)),
              '      { %s },' % f(tab), '      { %s } },' % f(nz[:, m])]
    return L + ['};']


if __name__ == '__main__':
    main()
