"""Writes plugins/WDelay/WDelayAnalogTables.h: H-Delay's Analog modes (measurements/hdelay/analog_model.json from
nulltest/fit_hc_analog2.py with ANALOG_PREFIX=hd, the noise from analog_noise.csv), in WComp's Analog format (mode 4
is H-Comp's: they null at -100 dB).

    python tools/export_wdelay_tables.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import export_wcomp_tables as W

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')


def main():
    W.M = os.path.join(ROOT, 'measurements', 'hdelay')
    def lit(t):
        s = '%.9g' % float(t)
        return (s if ('.' in s or 'e' in s) else s + '.0') + 'f'
    f = lambda v: ', '.join(lit(t) for t in v)
    body = W.analog(lit, f)
    # the format (counts, knots, the struct) is WComp's: keep only the table itself, in WDelay's namespace
    start = next(i for i, l in enumerate(body) if l.startswith('constexpr AnalogMode analog['))
    L = ['#pragma once', '// Generated by tools/export_wdelay_tables.py from measurements/hdelay (the reference H-Delay). Do not edit.',
         '#include "WCompTables.h"', 'namespace wdelay::tables', '{',
         '// H-Delay\'s Analog modes in WComp\'s format (wcomp::tables::AnalogMode); mode 4 is H-Comp\'s',
         'using wcomp::tables::AnalogMode;',
         body[start].replace('analogModes', 'wcomp::tables::analogModes')] + body[start + 1:] + ['}', '']
    out = os.path.join(ROOT, 'plugins', 'WDelay', 'WDelayAnalogTables.h')
    open(out, 'w', encoding='utf-8').write('\n'.join(L))
    print('wrote', out)


if __name__ == '__main__':
    main()
