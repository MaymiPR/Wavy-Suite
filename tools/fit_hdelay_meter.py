"""Fits the reference H-Delay's output meter housing (reference/hdelay/st_1_hover.png, git-ignored) as a shading model
WDelay draws: the frame (black outline to the window) as colour against the depth in from the outline, per side; the
window as a sum of three column profiles times row profiles (a rank-3 fit), the printed scale and the triangles masked
out by an iterative robust fit. Only fitted numbers are kept.

    python -I tools/fit_hdelay_meter.py   -> plugins/WDelay/WDelayMeterData.h
"""
import numpy as np
from PIL import Image

SHOT = 'reference/hdelay/st_1_hover.png'
OX0, OY0, OX1, OY1 = 600.0, 69.0, 646.0, 262.0         # the outline's outer edge (measured: black at x 600, 645, y 69, 261)
WX0, WY0, WX1, WY1 = 607.0, 76.0, 639.0, 254.0         # the window (inside the frame's dark inner line)
STEP, NBIN, NB, RANK = 1.0, 8, 8, 3


def frame_basis(x, y):
    d = np.stack([y - OY0, OY1 - y, x - OX0, OX1 - x], axis=-1)
    w = np.exp(-(d - d.min(axis=-1, keepdims=True)) / 0.5); w /= w.sum(axis=-1, keepdims=True)
    u = np.stack([(x - (OX0 + OX1) / 2) / ((OX1 - OX0) / 2)] * 2 + [(y - (OY0 + OY1) / 2) / ((OY1 - OY0) / 2)] * 2, axis=-1)
    return np.concatenate([w, w * u], axis=-1), d.min(axis=-1)


def main():
    I = np.asarray(Image.open(SHOT).convert('RGB')).astype(float)
    # the frame
    ys, xs = np.mgrid[int(OY0):int(OY1), int(OX0):int(OX1)]
    x = xs + 0.5; y = ys + 0.5
    win = (x > WX0) & (x < WX1) & (y > WY0) & (y < WY1)
    B, d = frame_basis(x, y)
    V = I[ys, xs]
    fr = np.zeros((NBIN, 3, NB))
    for b in range(NBIN):
        m = (np.floor(d / STEP) == b) & ~win
        if m.sum() < 8: fr[b] = fr[b - 1]; continue
        for ch in range(3):
            fr[b, ch] = np.linalg.solve(B[m].T @ B[m] + 0.5 * np.eye(NB), B[m].T @ V[m][:, ch] + 0.5 * (fr[b - 1, ch] if b else 0))
    bi = np.clip(np.floor(d / STEP).astype(int), 0, NBIN - 1)
    rec = np.stack([np.einsum('ijk,ijk->ij', fr[bi, ch], B) for ch in range(3)], axis=-1)
    print('frame rms %.2f' % np.sqrt(np.mean((rec[~win] - V[~win]) ** 2)))
    # the window: rank-3 per channel, robust
    W = I[int(WY0):int(WY1), int(WX0):int(WX1)]
    h, w = W.shape[:2]
    # the print masked out: every tick's rows at both sides, every number's box, the triangles at rest
    keep = np.ones((h, w), bool)
    yy, xx = np.mgrid[0:h, 0:w]; X = xx + WX0 + 0.5; Y = yy + WY0 + 0.5
    for t in (83.6, 108.7, 129.8, 162.7, 201.7, 221.6, 231.6):
        keep &= ~((np.abs(Y - t) < 3.0) & ((X < 615.5) | (X > 630.5)))
    for (y0, y1, x0, x1) in ((79, 88, 619, 626), (103, 112, 620, 626), (125, 134, 619, 626), (158, 167, 617, 629), (196, 205, 616, 630),
                             (216, 225, 616, 629), (228, 236, 616, 629), (238, 248, 607, 619), (238, 248, 628, 639)):
        keep &= ~((Y > y0 - 2) & (Y < y1 + 3) & (X > x0 - 2) & (X < x1 + 3))
    cols = np.zeros((3, RANK, w)); rows = np.zeros((3, RANK, h))
    for it in range(6):
        for ch in range(3):
            M = np.where(keep, W[..., ch], np.nan)
            # fill and factor: alternate least squares on the kept pixels
            A = np.nan_to_num(M, nan=np.nanmedian(M))
            U, S, Vt = np.linalg.svd(A, full_matrices=False)
            R = U[:, :RANK] * S[:RANK]; C = Vt[:RANK]
            for _ in range(20):
                for j in range(w):
                    k = keep[:, j]; C[:, j] = np.linalg.lstsq(R[k], W[k, j, ch], rcond=None)[0]
                good = np.zeros(h, bool)
                for i in range(h):
                    k = keep[i]
                    if k.sum() >= 6: R[i] = np.linalg.lstsq(C[:, k].T, W[i, k, ch], rcond=None)[0]; good[i] = True
                for kk in range(RANK):                    # rows hidden by the print: from their neighbours
                    R[~good, kk] = np.interp(np.flatnonzero(~good), np.flatnonzero(good), R[good, kk])
            rows[ch] = R.T; cols[ch] = C
        rec = np.stack([rows[ch].T @ cols[ch] for ch in range(3)], axis=-1)
        err = np.abs(rec - W).mean(axis=2)
        keep &= err < max(6.0, 3.0 * np.median(err[keep]))
    # the rows of masked lines are interpolated by the factors; smooth them a little (no print can remain)
    from scipy import ndimage
    rows = ndimage.gaussian_filter1d(rows, 0.8, axis=2)
    rec = np.stack([rows[ch].T @ cols[ch] for ch in range(3)], axis=-1)
    print('window rms (kept %.0f %%) %.2f' % (100 * keep.mean(), np.sqrt(np.mean((rec[keep] - W[keep]) ** 2))))
    lines = ['#pragma once', '// Generated by tools/fit_hdelay_meter.py from measurements of the reference meter housing. Do not edit.',
             '// Frame (600 .. 646 x 69 .. 262, the outline\'s outer edge, to the window 607 .. 639 x 76 .. 254): per 0.5 px of',
             '// depth, R, G, B as the sum over the sides (top, bottom, left, right) of w_k (c_k + c_k+4 u_k), w_k = exp(-(d_k -',
             '// d_min) / 0.5) normalised, u_k the position along the side (-1 .. 1). Window: R, G, B as the sum of 3 products',
             '// rows[ch][k][y] * cols[ch][k][x] (1 px each). All stored x 16.',
             '#include <cstdint>', 'namespace wdelay::meterdata', '{',
             'constexpr float ox0 = %.1ff, oy0 = %.1ff, ox1 = %.1ff, oy1 = %.1ff;' % (OX0, OY0, OX1, OY1),
             'constexpr float wx0 = %.1ff, wy0 = %.1ff, wx1 = %.1ff, wy1 = %.1ff;' % (WX0, WY0, WX1, WY1),
             'constexpr int frameBins = %d, frameTerms = %d, rank = %d, winW = %d, winH = %d;' % (NBIN, NB, RANK, w, h)]
    def arr(nm, a, k):
        lines.append('inline constexpr int16_t %s[] = {%s};' % (nm, ','.join(str(int(v)) for v in np.clip(np.round(a.ravel() * k), -32767, 32767))))
    arr('frame', fr, 16)
    # scale the factors so both are near unit range: rows carry the brightness
    sc = np.abs(cols).max(axis=2, keepdims=True) + 1e-9
    arr('cols', cols / sc, 16000 / 16)
    arr('rows', rows * sc[..., 0][..., None], 16)
    lines.append('constexpr float colScale = %.1ff;' % (16000 / 16))
    lines.append('}')
    with open('plugins/WDelay/WDelayMeterData.h', 'w', newline='\n') as f: f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
