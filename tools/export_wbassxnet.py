"""Writes plugins/WBassX/WBassXNet.h: the trained level-control GRU (build/wbassxnet/net_h<H>.pt) and the measured
output scale K(F) per whole-Hz Freq setting (measurements/maxxbass/k_out_table.json).

    <torch python> tools/export_wbassxnet.py [hidden] [weights.pt]
"""
import sys, os, json
import torch

HERE = os.path.dirname(os.path.abspath(__file__))
H = int(sys.argv[1]) if len(sys.argv) > 1 else 32
src = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "..", "build", "wbassxnet", f"net_h{H}_e2e.pt")
sd = torch.load(src, map_location="cpu")
kt = json.load(open(os.path.join(HERE, "..", "measurements", "maxxbass", "k_out_table.json")))
K = [kt[str(F)][0] for F in range(32, 257)]


def arr(name, t):
    v = t.flatten().tolist()
    body = ",\n    ".join(", ".join("%.9gf" % x for x in v[i:i + 8]) for i in range(0, len(v), 8))
    return "inline constexpr float %s[%d] = {\n    %s };\n" % (name, len(v), body)


with open(os.path.join(HERE, "..", "plugins", "WBassX", "WBassXNet.h"), "w", newline="\n") as f:
    f.write("#pragma once\n// Generated by tools/export_wbassxnet.py: the WBassX level-control GRU (trained by nulltest/train_wbassx.py on\n"
            "// gains extracted from reference renders) and the measured output scale K(F). Do not edit.\nnamespace wbassx::net\n{\n")
    f.write("inline constexpr int hidden = %d, inputs = %d;\n" % (H, sd["gru.weight_ih_l0"].shape[1]))
    f.write(arr("Wih", sd["gru.weight_ih_l0"])); f.write(arr("Whh", sd["gru.weight_hh_l0"]))
    f.write(arr("bih", sd["gru.bias_ih_l0"])); f.write(arr("bhh", sd["gru.bias_hh_l0"]))
    f.write(arr("Wout", sd["out.weight"])); f.write("inline constexpr float bout = %.9gf;\n" % float(sd["out.bias"][0]))
    f.write("// output scale of the generated part, Freq 32 ... 256 Hz in 1 Hz steps\n")
    body = ",\n    ".join(", ".join("%.6f" % x for x in K[i:i + 8]) for i in range(0, len(K), 8))
    f.write("inline constexpr double kOut[%d] = {\n    %s };\n}\n" % (len(K), body))
print("wrote WBassXNet.h, hidden", H, "from", src)
