"""Writes plugins/WVoxRider/WVoxRiderFit.h: the riding model's constants, the reference's hidden values
(nulltest/vrmodel.py DEFAULTS), or with --fit the local fit (measurements/wvoxrider/riding_fit.json, written by
nulltest/vr_fit.py).

    python -I tools/vr_export.py [--fit]
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'nulltest'))
import vrmodel as M

FIT = os.path.join(HERE, '..', 'measurements', 'wvoxrider', 'riding_fit.json')
OUT = os.path.join(HERE, '..', 'plugins', 'WVoxRider', 'WVoxRiderFit.h')
p = dict(M.DEFAULTS)
src = "the reference's hidden values (nulltest/vrmodel.py DEFAULTS)"
if '--fit' in sys.argv:
    d = json.load(open(FIT)); p.update(d['params']); src = 'measurements/wvoxrider/riding_fit.json (mean null %.2f dB)' % d['cost']
names = [('c', 'c'), ('bias', 'bias'), ('followerAttackSlow', 'fatt_s'), ('followerAttackFast', 'fatt_f'), ('followerRelease', 'frel'),
         ('followerHold', 'fhold'), ('followerPower', 'fpow'), ('vadAttack', 'vatt'), ('vadRelease', 'vrel'), ('vk', 'vk'),
         ('rideAttackSlow', 'ratt_s'), ('rideAttackFast', 'ratt_f'), ('rideRelease', 'rrel'),
         ('ridePower', 'rpow'), ('parkTime', 'park'), ('parkHoldSlow', 'phold_s'), ('parkHoldFast', 'phold_f'), ('spillOffset', 'spill'),
         ('initialV', 'v0')]
lines = ['#pragma once', '// Generated by tools/vr_export.py from %s. Do not edit.' % src,
         '// Times in ms, levels in dB (nulltest/vrmodel.c names in brackets).', 'namespace wvoxrider::fit', '{']
for cpp, py in names: lines.append('inline constexpr double %s = %.6g;   // [%s]' % (cpp, p[py], py))
lines += ['}', '']
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
print('wrote', OUT, 'from', src)
