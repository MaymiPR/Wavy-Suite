"""Phase 4: Bass and Treble. For each colour and each of the 21 fader steps, the reference's response over the chain with
every colour clear (complex, 1/12 octave, from campaign_voxchain.py's single.json) is fitted with analog sections
(RBJ-style low / high shelves, bells, a second-order high-pass), bilinear transformed with prewarping at 48 kHz; the
per-step parameters (frequency, Q, gain) make a table the plug-in interpolates over the fader. Writes
plugins/WVoxChain/WVoxChainEq.h and prints each fit's worst error (dB) over 30 Hz .. 16 kHz.

    python -I fit_voxchain_eq.py
"""
import json
import os
import sys
import numpy as np
from scipy.optimize import least_squares

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from campaign_voxchain import FREQS
OUT = os.path.join(HERE, '..', 'plugins', 'WVoxChain', 'WVoxChainEq.h')
FS = 48000.0
BAND = (FREQS >= 25) & (FREQS <= 18000)
# each colour's sections: (type, initial frequency, initial Q); 'hp' a second-order high-pass (no gain)
LAYOUT = {
    ('bass', 1): [('ls', 60.0, 0.7), ('pk', 120.0, 0.8), ('hp', 40.0, 0.6)],
    ('bass', 2): [('ls', 100.0, 0.7), ('pk', 150.0, 0.8), ('hp', 40.0, 0.6)],
    ('bass', 3): [('ls', 100.0, 0.7), ('pk', 900.0, 0.7), ('hp', 40.0, 0.7), ('hp', 40.0, 1.3)],
    ('treble', 1): [('pk', 5000.0, 1.0), ('pk', 9000.0, 0.7)],
    ('treble', 2): [('hs', 5000.0, 0.7), ('pk', 12000.0, 0.7)],
    ('treble', 3): [('hs', 8000.0, 0.7), ('pk', 600.0, 0.7)],
}


def biquad(kind, f0, q, gdb, fs=FS):
    """RBJ cookbook coefficients (b, a) with the frequency prewarped (the bilinear transform's own)"""
    A = 10 ** (gdb / 40); w = 2 * np.pi * f0 / fs; cw, sw = np.cos(w), np.sin(w); al = sw / (2 * q)
    if kind == 'pk':
        b = [1 + al * A, -2 * cw, 1 - al * A]; a = [1 + al / A, -2 * cw, 1 - al / A]
    elif kind == 'ls':
        s = 2 * np.sqrt(A) * al
        b = [A * ((A + 1) - (A - 1) * cw + s), 2 * A * ((A - 1) - (A + 1) * cw), A * ((A + 1) - (A - 1) * cw - s)]
        a = [(A + 1) + (A - 1) * cw + s, -2 * ((A - 1) + (A + 1) * cw), (A + 1) + (A - 1) * cw - s]
    elif kind == 'hs':
        s = 2 * np.sqrt(A) * al
        b = [A * ((A + 1) + (A - 1) * cw + s), -2 * A * ((A - 1) + (A + 1) * cw), A * ((A + 1) + (A - 1) * cw - s)]
        a = [(A + 1) - (A - 1) * cw + s, 2 * ((A - 1) - (A + 1) * cw), (A + 1) - (A - 1) * cw - s]
    elif kind == 'hp':
        b = [(1 + cw) / 2, -(1 + cw), (1 + cw) / 2]; a = [1 + al, -2 * cw, 1 - al]
    b = np.array(b) / a[0]; a = np.array(a) / a[0]
    return b, a


def resp(b, a, f, fs=FS):
    z = np.exp(-1j * 2 * np.pi * f / fs)
    return (b[0] + b[1] * z + b[2] * z * z) / (a[0] + a[1] * z + a[2] * z * z)


def model(params, layout, f, hp_on=True):
    H = np.ones(len(f), complex)
    i = 0
    for kind, _, _ in layout:
        if kind == 'hp':
            fr, q = params[i], params[i + 1]; i += 2
            if hp_on: H *= resp(*biquad('hp', fr, q, 0.0), f)
        else:
            fr, q, g = params[i], params[i + 1], params[i + 2]; i += 3
            H *= resp(*biquad(kind, fr, q, g), f)
    return H


def fit_one(target, layout, init, hp_on):
    lo, hi = [], []
    for kind, f0, q in layout:
        lo += [10.0, 0.1]; hi += [22000.0, 8.0]
        if kind != 'hp': lo.append(-30.0); hi.append(30.0)
    def res(p):
        H = model(p, layout, FREQS, hp_on)
        d = np.log(H[BAND]) - np.log(target[BAND])
        d = np.concatenate([d.real * 8.686, np.angle(np.exp(1j * d.imag)) * 20.0])   # dB, and phase (rad x 20)
        return d
    init = np.clip(init, np.array(lo) + 1e-6, np.array(hi) - 1e-6)
    sol = least_squares(res, init, bounds=(lo, hi), x_scale='jac', max_nfev=4000)
    H = model(sol.x, layout, FREQS, hp_on)
    worst = np.max(np.abs(20 * np.log10(np.abs(H[BAND]) / np.abs(target[BAND]))))
    return sol.x, worst


def main():
    S = json.load(open(os.path.join(HERE, '..', 'reference', 'wvoxchain', 'meas', 'campaign', 'single.json')))
    clear = next(r for r in S if r['kind'] == 'tf' and r['stage'] == 'clear')
    H0 = 10 ** (np.array(clear['magL']) / 20) * np.exp(1j * np.array(clear['phL']))
    lines = ['#pragma once', '// Generated by nulltest/fit_voxchain_eq.py: Bass and Treble per colour, the sections\' parameters at each',
             '// fader step -10 .. +10 (frequency Hz, Q, gain dB; a high-pass: frequency, Q, 0), fitted to the reference\'s',
             '// responses over the chain with every colour clear. Do not edit.', 'namespace wvoxchain::eq', '{',
             'enum Kind { lowShelf, peak, highShelf, highPass };', 'struct Section { Kind kind; float f[21], q[21], g[21]; };',
             'struct Colour { int n; Section s[4]; bool hpFromZero; };   // hpFromZero: the high-pass only at fader 0 and above']
    kinds = {'ls': 'lowShelf', 'pk': 'peak', 'hs': 'highShelf', 'hp': 'highPass'}
    for (st, col), layout in LAYOUT.items():
        rows = sorted((r for r in S if r['kind'] == 'tf' and r['stage'] == st and r['colour'] == col), key=lambda r: r['fader'])
        init = []
        for kind, f0, q in layout:
            init += [f0, q] + ([0.0] if kind != 'hp' else [])
        P = {}
        worst = []
        # fit from 0 outwards, each step starting from its neighbour's fit
        order = [10] + [10 + k for k in range(1, 11)] + [10 - k for k in range(1, 11)]
        for idx in order:
            r = rows[idx]
            T = 10 ** (np.array(r['magL']) / 20) * np.exp(1j * np.array(r['phL'])) / H0
            hp_on = not (st == 'bass' and col == 3 and r['fader'] < 0)
            starts = [P[idx - 1] if idx > 10 else (P[idx + 1] if idx < 10 else np.array(init))]
            rng = np.random.default_rng(idx)
            for _ in range(10):                                   # (and random starts round the layout's)
                s0 = []
                for kind, f0, q in layout:
                    s0 += [f0 * rng.uniform(0.5, 2.0), q * rng.uniform(0.6, 1.8)] + ([rng.uniform(-12, 12)] if kind != 'hp' else [])
                starts.append(np.array(s0))
            p, w = min((fit_one(T, layout, s0, hp_on) for s0 in starts), key=lambda t: t[1])
            P[idx] = p; worst.append((r['fader'], w))
        worst.sort()
        print('%-6s colour %d: worst error per step %s (max %.2f dB)' % (st, col, ' '.join('%.2f' % w for _, w in worst), max(w for _, w in worst)))
        name = '%s%d' % (st, col)
        secs = []
        i = 0
        for kind, _, _ in layout:
            n = 2 if kind == 'hp' else 3
            fr = [P[k][i] for k in range(21)]; q = [P[k][i + 1] for k in range(21)]
            g = [P[k][i + 2] if n == 3 else 0.0 for k in range(21)]
            i += n
            secs.append('{ %s, { %s }, { %s }, { %s } }' % (kinds[kind], ', '.join('%.3ff' % v for v in fr), ', '.join('%.4ff' % v for v in q), ', '.join('%.4ff' % v for v in g)))
        lines.append('inline constexpr Colour %s { %d, { %s }, %s };' % (name, len(layout), ', '.join(secs), 'true' if (st, col) == ('bass', 3) else 'false'))
    lines += ['inline constexpr const Colour* bass[4] = { nullptr, &bass1, &bass2, &bass3 };',
              'inline constexpr const Colour* treble[4] = { nullptr, &treble1, &treble2, &treble3 };', '}', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
