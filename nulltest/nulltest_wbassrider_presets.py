"""WBass Rider's factory presets against the reference's own (build/ref_presets_BassRider.json, nulltest/read_ref_presets_br.py):
each preset's values set on both (Target left at its default where the preset keeps it), on the bass line and two
held-out corpus parts; the output residual over the loud parts. Writes docs/NULL_RESULTS_WBASSRIDER_PRESETS.md.

    python -I nulltest_wbassrider_presets.py
"""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import measure_bassrider as M, nulltest_wbassrider as N, brcompare as C, bass_corpus as K

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'build', 'ref_presets_BassRider.json')
OUT = os.path.join(HERE, '..', 'docs', 'NULL_RESULTS_WBASSRIDER_PRESETS.md')
sys.path.insert(0, os.path.join(HERE, '..', 'tools'))
import importlib.util
spec = importlib.util.spec_from_file_location('mp', os.path.join(HERE, '..', 'tools', 'make_presets.py'))


def settings(raw):
    get = lambda i: float(raw[i])
    st = dict(output=get(4), range_min=get(8), range_max=get(9), sensitivity=get(31), response='Fast' if get(33) > 0.5 else 'Slow',
              artifacts=(get(44) + 20.0) / 17.0 * 100.0, spill=get(45))
    if raw[12] != '*': st['target'] = get(12)
    return st, get(34)


def residual(x, y, r):
    env = np.convolve(x.astype(float) ** 2, np.ones(96) / 96, 'same'); ok = env > 10 ** (-60 / 10); ok[:4800] = False
    return 10 * np.log10(np.sum((y - r)[ok] ** 2) / np.sum(r[ok] ** 2) + 1e-30)


def main():
    data = json.load(open(SRC))
    names = None
    src = open(os.path.join(HERE, '..', 'tools', 'make_presets.py'), encoding='utf-8').read()
    names = eval(src[src.index('BASSRIDER_NAMES = [') + len('BASSRIDER_NAMES = '):src.index(']', src.index('BASSRIDER_NAMES = [')) + 1])
    mats = [('bass line', C.bassline().astype(np.float32)), ('corpus part 30 (picked)', K.part(30)[0]), ('corpus part 25 (slap)', K.part(25)[0])]
    rows = []
    for name, d in zip(names, data):
        st, frac = settings(d['raw'])
        res = []
        for mname, x in mats:
            ref_st = dict(st, idle=float(np.clip(-12.0 + 24.0 * frac, -11.5, 11.5)))
            ref_st['response'] = st['response'] + ' '
            r = M.render(x, **ref_st)
            ours_st = dict(st, idle=st['range_min'] + frac * (st['range_max'] - st['range_min']))
            y = N.render_ours(x[None], **{k: (v + ' ' if k == 'response' else v) for k, v in ours_st.items()})[0]
            res.append(residual(x, y, r))
        rows.append((name, res)); print('%-26s ' % name + '  '.join('%6.1f' % v for v in res), flush=True)
    allv = np.array([v for _, r in rows for v in r])
    lines = ['# WBass Rider: factory presets against the reference', '',
             'Each of the reference\'s 17 presets set on both plug-ins (Wavy names; Target at its default where the preset',
             'leaves it), output residual over the loud parts in dB (lower is better). Generated by',
             '`nulltest/nulltest_wbassrider_presets.py`.', '',
             '| preset | ' + ' | '.join(m for m, _ in mats) + ' |', '|---|' + '---|' * len(mats)]
    lines += ['| %s | %s |' % (n, ' | '.join('%.1f' % v for v in r)) for n, r in rows]
    lines += ['', 'Median %.1f dB, worst %.1f dB.' % (np.median(allv), allv.max()), '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print('median %.1f, worst %.1f -> %s' % (np.median(allv), allv.max(), OUT))


if __name__ == '__main__':
    main()
