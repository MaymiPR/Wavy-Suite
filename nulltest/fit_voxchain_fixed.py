"""Phase 4: the chain's fixed filter (every colour clear, at a linear level) per sample rate: an order-6 IIR fitted
(Steiglitz-McBride) to the reference's impulse response at 44.1 / 48 / 88.2 / 96 kHz (captured by cv_ref into the
git-ignored reference/wvoxchain/meas/clear_ir_<rate>.npy). Its two first-order all-passes sit at the same frequencies
(about 1.95 and 6.4 kHz) at every rate, but a section near the top of the band does not, so the filter is kept per rate
rather than as one analog prototype. Writes plugins/WVoxChain/WVoxChainFixed.h (second-order sections).

    python -I fit_voxchain_fixed.py
"""
import os
import numpy as np
from scipy.signal import lfilter, tf2sos, sosfilt

HERE = os.path.dirname(os.path.abspath(__file__))
RATES = (44100, 48000, 88200, 96000)
OUT = os.path.join(HERE, '..', 'plugins', 'WVoxChain', 'WVoxChainFixed.h')


def stmcb(h, nb, na, it=60):
    N = len(h); x = np.zeros(N); x[0] = 1; a = np.ones(1)
    for _ in range(it):
        xf = lfilter([1], a, x); hf = lfilter([1], a, h)
        cols = [np.concatenate([np.zeros(i), xf[:N - i]]) for i in range(nb + 1)] + \
               [-np.concatenate([np.zeros(i), hf[:N - i]]) for i in range(1, na + 1)]
        th = np.linalg.lstsq(np.stack(cols, 1), hf, rcond=None)[0]
        b = th[:nb + 1]; a = np.concatenate([[1], th[nb + 1:]])
    return b, a


def main():
    lines = ['#pragma once', '// Generated by nulltest/fit_voxchain_fixed.py: the chain\'s fixed filter (every colour clear) per sample',
             '// rate, second-order sections b0 b1 b2 a1 a2 (a0 = 1), fitted to the reference\'s impulse responses. Do not edit.',
             'namespace wvoxchain::fixed', '{', 'struct Rate { double fs; double sos[3][5]; };', 'inline constexpr Rate rates[] = {']
    for fs in RATES:
        h = np.load(os.path.join(HERE, '..', 'reference', 'wvoxchain', 'meas', 'clear_ir_%d.npy' % fs))[64:64 + 4096].astype(float)
        b, a = stmcb(h, 6, 6)
        sos = tf2sos(b, a)
        d = np.zeros(len(h)); d[0] = 1
        e = 10 * np.log10(np.sum((sosfilt(sos, d) - h) ** 2) / np.sum(h ** 2))
        print('%6d Hz: error %.1f dB, poles |max| %.4f' % (fs, e, np.abs(np.roots(a)).max()))
        rows = ', '.join('{ %s }' % ', '.join('%.12g' % v for v in (s[0], s[1], s[2], s[4], s[5])) for s in sos)
        lines.append('    { %d.0, { %s } },' % (fs, rows))
    lines += ['};', '}', '']
    open(OUT, 'w').write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
